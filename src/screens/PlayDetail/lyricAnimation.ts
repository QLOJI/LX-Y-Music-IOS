// 播放详情页（大歌词 / 小歌词 / 手动定位浮层）动效时长的**单一来源**。
//
// 此前这些时长在各文件里各写各的魔数（换行滑动 180、seek 过渡 180、回位 120~300…），
// 导致「按大歌词的速率」这类要求无处落地，全局调速也要逐文件改。现统一收口到这里，
// 实际数值一律取自 designMotion.quick（2026-10-01：150 → 200，全局放慢）。
// 新增歌词相关动画请引用本文件，不要再内联数字。
// 例外一处：LINE_CHANGE_HOLD_MS（大歌词换行停留）2026-10-13 第 73 轮起不再等于
// designMotion.quick，改为它的一半 —— 原因见其定义处的【第 73 轮】说明。

import { designMotion } from '@/theme/DesignTokens'

/** 歌词换行时，当前行滑到居中位置的时长（大歌词与小歌词同值）。 */
export const LINE_CHANGE_GLIDE_MS = designMotion.quick

/**
 * 【第 30 轮】连续换行（diff==1）后、起滑之前的「停留」时长。
 *
 * 大歌词（竖屏 / 横屏）此前是 REF 参考工程的 600ms 停留 + 600ms 滑动，用户报
 * 「逐词加载完到下一行，换行动画有很大延迟」—— 卡顿感全部来自这 600ms 的停顿
 * （滑动本身是 easeInOutQuad，是顺滑的）。现在收口到 designMotion.quick(200)：
 * 停留 200 + 滑动 RETURN_TO_ACTIVE_MS(600)，换行节奏由 1.2s 缩短到 0.8s，观感不再是
 * 「停一下再走」。停留窗口的语义不变（锚定在一串连续换行的第一行、串内不重置）。
 *
 * 【第 73 轮】用户再次报「歌词换行响应再快点」，200 → 100（不再是 designMotion.quick）。
 * 换行的「响应」延迟就是这个停留窗口本身：换行当帧列表纹丝不动（这是停留窗口的定义，
 * 见 Vertical/Lyric.tsx 的 holdElapsed 分支），要等窗口到点才起滑。滑动时长
 * RETURN_TO_ACTIVE_MS(600) 是参考工程的定案值、且与小歌词回位同源（契约钉死值），
 * 不能动 —— 所以「响应更快」只能从停留这一段里挤，这也是第 30 轮把 600 砍到 200 的同一个旋钮。
 * 100 仍高于 60Hz 下的两帧（起滑时刻不会被同一帧吞掉），REF「先停留、再起滑」的节奏
 * 也还在（观感仍是一顿一滑，不是立刻滑），只是起滑比原来提前一半：停留 100 + 滑动 600，
 * 整周期 0.8s → 0.7s，快歌里「唱到下一行」与「列表开始动」之间的空档几乎察觉不到。
 * 横竖屏两个大歌词共用本值（同源口径不变）；小歌词换行跟随走的是 LINE_CHANGE_GLIDE_MS，
 * 它的「换行响应」没有停留段，本值不影响它。
 */
export const LINE_CHANGE_HOLD_MS = 100

/** 手动拖动歌词结束、停手多久后自动回位并隐藏定位浮层。用户要求「未滑动响应时间缩短一半」，故由 3000 改为 1500。 */
export const IDLE_RETURN_MS = 1500

/**
 * 【第 55 轮第 1 条】大歌词「双击跳转播放」的判定窗口（ms）。
 *
 * 用户报「单击歌词就跳转播放」是误触来源，要求取消单击跳转：要么只留浮层右侧的播放三角，
 * 要么改成双击才跳。定案是**双击**（三角按钮保留原样，两条路都在）。
 * 窗口取 300：iOS 系统双击手势的常用判定值；两次点击必须落在**同一行**且间隔 < 300ms
 * 才算一次双击，间隔超时或换行点击都按「新的第一次」重新计时。
 *
 * 这不是动画时长，但和上面几个常量一样是「歌词交互的全局单一来源」：
 * 竖屏 / 横屏两个大歌词共用本值，改一处两边同步（同 RETURN_TO_ACTIVE_MS 的口径）。
 * 小歌词（MiniLyric）**不参与**：它的单击是「切到歌词页」，要加双击就得给单击加 300ms
 * 延迟，用户明确说只改大歌词。
 */
export const LYRIC_DOUBLE_TAP_MS = 300

/** 定位浮层（虚线 + 时间 + 播放三角）显隐的淡入淡出时长。 */
export const OVERLAY_FADE_MS = designMotion.quick

/**
 * 手动滑动后「回位到正在播放的那一行」的时长（与竖屏大歌词的回位滑动同值同源）。
 *
 * 竖屏大歌词的回位不是另起一套动画：停手后它往连续滚动循环里排一个 glide 任务，
 * 走的就是换行滑动那条 easeInOutQuad、固定 600ms（Vertical/Lyric.tsx 的
 * LINE_CHANGE_GLIDE_REF_MS，需求 #1 对齐参考工程的定案值）。
 * 小歌词（MiniLyric）此前按距离取 [120, 300]，同屏一比就是「小歌词回位窜得快」
 * —— 用户报的「小歌词滑动后返回播放进度时，动画速度和大歌词不一致」。
 * 现在两边共同引用本常量：改一处两边同步，不会再各自漂移。
 * （曲线两边同为 easeInOutQuad，只差时长，所以对齐时长即完全同速。）
 */
export const RETURN_TO_ACTIVE_MS = 600

/**
 * 自动回位动画的时长：随距离线性增长并夹在 [120, 300] 内，远距离不会拖沓。
 *
 * 注意：**竖屏大歌词与小歌词的回位不用它**（两者必须同速，见 RETURN_TO_ACTIVE_MS）；
 * 目前只有横屏大歌词的回位/跟随在用，别拿它去改小歌词。
 */
export const getReturnDuration = (distance: number) =>
  Math.min(Math.max(Math.abs(distance) * 0.5, 120), 300)
