// 播放详情页（大歌词 / 小歌词 / 手动定位浮层）动效时长的**单一来源**。
// 新增歌词相关动画请引用本文件，不要再内联数字。

import { designMotion } from '@/theme/DesignTokens'

/** 歌词换行时，当前行滑到居中位置的时长（大歌词与小歌词同值）。 */
export const LINE_CHANGE_GLIDE_MS = designMotion.quick

/**
 * 连续换行（diff==1）后、起滑之前的「停留」时长（大歌词竖/横屏共用）。
 * 换行的「响应」延迟就是这个窗口本身：窗口内列表纹丝不动，到点才起滑
 * （见 Vertical/Lyric.tsx 的 holdElapsed 分支）。小歌词换行跟随没有停留段，不受本值影响。
 *
 * REF 600 → 第 30 轮 200 → 第 73 轮 100 →【第 76 轮】60：用户三次报「换行慢/延迟大」。
 * 60 仍高于 60Hz 下的两帧，起滑时刻不会被同一帧吞掉，「先停留、再起滑」的节奏还在。
 */
export const LINE_CHANGE_HOLD_MS = 60

/** 手动拖动歌词结束、停手多久后自动回位并隐藏定位浮层。用户要求「未滑动响应时间缩短一半」，故由 3000 改为 1500。 */
export const IDLE_RETURN_MS = 1500

/**
 * 【第 55 轮第 1 条】大歌词「双击跳转播放」的判定窗口（ms）。
 *
 * 用户报「单击歌词就跳转播放」是误触来源，要求取消单击跳转：要么只留浮层右侧的播放三角，
 * 要么改成双击才跳。定案是**双击**（三角按钮保留原样，两条路都在）。
 * 窗口取 300：iOS 系统双击手势的常用判定值；两次点击必须落在**同一行**且间隔 < 300ms
 * 才算一次双击，间隔超时或换行点击都按「新的第一次」重新计时。
 *
 * 这不是动画时长，但和上面几个常量一样是「歌词交互的全局单一来源」：
 * 竖屏 / 横屏两个大歌词共用本值，改一处两边同步（同 RETURN_TO_ACTIVE_MS 的口径）。
 * 小歌词（MiniLyric）**不参与**：它的单击是「切到歌词页」，要加双击就得给单击加 300ms
 * 延迟，用户明确说只改大歌词。
 */
export const LYRIC_DOUBLE_TAP_MS = 300

/** 定位浮层（虚线 + 时间 + 播放三角）显隐的淡入淡出时长。 */
export const OVERLAY_FADE_MS = designMotion.quick

/**
 * 大歌词换行滑动 / 「回位到正在播放的那一行」的时长 —— 大歌词与小歌词**同源同值**
 * （两边曲线同为 easeInOutQuad，时长相同即完全同速；小歌词若按距离取值就会「窜得快」）。
 *
 * 【第 76 轮】600 → 400：用户「歌词换行动画速度再快点，之前提过速，但是还是有点慢」。
 * 这一档就是换行动画里那段滑动的时长（停留那一段另见 LINE_CHANGE_HOLD_MS），
 * 同源口径不变 —— 提速后小歌词回位跟着一起变快，两边仍同速。
 */
export const RETURN_TO_ACTIVE_MS = 400

/**
 * 自动回位动画的时长：随距离线性增长并夹在 [120, 300] 内，远距离不会拖沓。
 *
 * 注意：**竖屏大歌词与小歌词的回位不用它**（两者必须同速，见 RETURN_TO_ACTIVE_MS）；
 * 目前只有横屏大歌词的回位/跟随在用，别拿它去改小歌词。
 */
export const getReturnDuration = (distance: number) =>
  Math.min(Math.max(Math.abs(distance) * 0.5, 120), 300)
